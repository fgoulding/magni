// @vitest-environment jsdom
import "@testing-library/jest-dom/vitest";
import { useState } from "react";
import { cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { createBlankDocument, createDay, createExercise, createSet, type ProgramDocumentV1 } from "@/features/program-editor/document";
import { makePreset } from "@/features/program-editor/operations";
import { ProgramBuilder } from "./ProgramBuilder";
afterEach(cleanup);
function Harness({ initial = createBlankDocument(), onDocumentChange }: { initial?: ProgramDocumentV1; onDocumentChange?: (document: ProgramDocumentV1) => void }) {
  const [document, setDocument] = useState(initial);
  return <ProgramBuilder document={document} onChange={update => setDocument(current => { const next = structuredClone(current); update(next); onDocumentChange?.(next); return next; })} onActivate={vi.fn()} activating={false} activeId={null} onAdvanced={vi.fn()} onExport={vi.fn()} />;
}
describe("day-based program builder", () => {
  it("collapses without edits and preserves that group's state through reordering and day navigation", () => {
    const initial = makePreset("manual-ab", "2026-10-13");
    initial.weeks[0].days[0].exercises.push(createExercise("Calf raise"));
    initial.weeks[0].days[0].exercises[0].sets.forEach(set => { set.tempo = "3-1-1"; set.notes = "Keep the shoulder controlled."; });
    const changed = vi.fn();
    render(<Harness initial={initial} onDocumentChange={changed} />);
    const firstName = screen.getAllByLabelText("Exercise name")[0];
    fireEvent.change(firstName, { target: { value: "Weighted pull-up" } });
    changed.mockClear();
    const disclosure = screen.getByRole("button", { name: "Collapse Superset A" });
    expect(disclosure).toHaveAttribute("aria-expanded", "true");
    fireEvent.click(disclosure);
    expect(firstName).not.toBeVisible();
    expect(screen.getByLabelText("Superset A summary")).toHaveTextContent("Weighted pull-up");
    expect(screen.getByLabelText("Superset A summary")).toHaveTextContent("Tempo 3-1-1");
    expect(screen.getByLabelText("Superset A summary")).toHaveTextContent("Keep the shoulder controlled.");
    expect(changed).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole("button", { name: "Move superset A later" }));
    expect(changed).toHaveBeenCalledTimes(1);
    expect(screen.getByRole("button", { name: "Expand Superset A" })).toHaveAttribute("aria-expanded", "false");
    changed.mockClear();
    fireEvent.click(screen.getByRole("button", { name: "Move day later" }));
    expect(changed).toHaveBeenCalledTimes(1);
    expect(screen.getByRole("button", { name: "Expand Superset A" })).toHaveAttribute("aria-expanded", "false");
    changed.mockClear();
    fireEvent.change(screen.getByRole("combobox", { name: "Day" }), { target: { value: "0" } });
    expect(screen.getByRole("button", { name: "Collapse Superset B" })).toHaveAttribute("aria-expanded", "true");
    fireEvent.change(screen.getByRole("combobox", { name: "Day" }), { target: { value: "1" } });
    fireEvent.click(screen.getByRole("button", { name: "Expand Superset A" }));
    expect(screen.getByDisplayValue("Weighted pull-up")).toBeVisible();
    expect(changed).not.toHaveBeenCalled();
  });
  it("reveals a closed destination superset and preserves focus while editing membership", () => {
    const initial = makePreset("manual-ab", "2026-10-13");
    initial.weeks[0].days[0].exercises.push(createExercise("Calf raise"));
    const changed = vi.fn();
    render(<Harness initial={initial} onDocumentChange={changed} />);
    fireEvent.click(screen.getByRole("button", { name: "Collapse Superset A" }));
    const source = screen.getByRole("group", { name: "Exercise 1: Calf raise" });
    fireEvent.click(within(source).getByText("Details", { selector: "summary" }));
    const group = within(source).getByLabelText("Superset group");
    group.focus();
    fireEvent.change(group, { target: { value: "A" } });
    expect(changed).toHaveBeenCalledTimes(1);
    expect(screen.getByRole("button", { name: "Collapse Superset A" })).toHaveAttribute("aria-expanded", "true");
    const moved = screen.getByRole("group", { name: "Exercise 3: Calf raise" });
    const movedGroup = within(moved).getByLabelText("Superset group");
    expect(movedGroup).toBeVisible(); expect(movedGroup).toHaveFocus();
    fireEvent.change(movedGroup, { target: { value: "AB" } });
    const renamed = screen.getByRole("group", { name: "Exercise 1: Calf raise" });
    expect(within(renamed).getByLabelText("Superset group")).toBeVisible();
    expect(within(renamed).getByLabelText("Superset group")).toHaveFocus();
    expect(changed).toHaveBeenCalledTimes(2);
  });
  it("keeps mixed set roles and every loading mode truthful in closed summaries", () => {
    const initial = makePreset("top-backoff", "2026-10-13");
    const exercise = initial.weeks[0].days[0].exercises[0];
    exercise.sets[0].tempo = "2-1-1"; exercise.sets[0].notes = "Pause at depth.";
    exercise.sets.push({ ...createSet(), loadMode: "percent", load: 65 }, { ...createSet(), loadMode: "bodyweight" }, { ...createSet(), loadMode: "added", load: 12.5 });
    render(<Harness initial={initial} />);
    fireEvent.click(screen.getByRole("button", { name: "Collapse Squat" }));
    const summary = screen.getByLabelText("Squat summary");
    expect(summary).toHaveTextContent("Squat · 6 sets");
    expect(within(summary).getByText("Individual sets")).toBeVisible();
    expect(within(summary).getAllByRole("listitem")[0]).toHaveTextContent(/Top set.*RPE 8.*Tempo 2-1-1.*Pause at depth/);
    expect(summary).toHaveTextContent("1. Top set · 5–8 reps · 135 lb");
    expect(summary).toHaveTextContent("2. Back-off · 8 reps · 115 lb fixed");
    expect(summary).toHaveTextContent("4. Work set · 8–12 reps · 65% of max");
    expect(summary).toHaveTextContent("5. Work set · 8–12 reps · Bodyweight");
    expect(summary).toHaveTextContent("6. Work set · 8–12 reps · 12.5 lb added");
  });
  it("reuses complete prescriptions independently, remaps designated targets, and focuses the new exercise", () => {
    const initial = makePreset("top-backoff", "2026-10-13");
    const source = initial.weeks[0].days[0].exercises[0];
    source.supersetGroup = "A"; source.notes = "Authored technique"; source.sets[0].tempo = "3-1-1";
    const before = structuredClone(source);
    initial.weeks[0].days.push(createDay("New day"));
    const changed = vi.fn();
    render(<Harness initial={initial} onDocumentChange={changed} />);
    fireEvent.change(screen.getByRole("combobox", { name: "Day" }), { target: { value: "1" } });
    fireEvent.click(screen.getByText("Reuse an exercise"));
    fireEvent.change(screen.getByRole("combobox", { name: "Exercise to reuse" }), { target: { value: source.id } });
    fireEvent.click(screen.getByRole("button", { name: "Add independent copy" }));
    expect(changed).toHaveBeenCalledTimes(1);
    const after = changed.mock.calls[0][0] as ProgramDocumentV1;
    expect(after.weeks[0].days[0].exercises[0]).toEqual(before);
    const copied = after.weeks[0].days[1].exercises[0];
    expect(copied.id).not.toBe(source.id); expect(copied.progressionKey).not.toBe(source.progressionKey);
    expect(copied.historyKey).toBe(source.historyKey); expect(copied.supersetGroup).toBe("");
    expect(copied.notes).toBe(source.notes);
    expect(copied.sets.map(set => ({ ...set, id: "" }))).toEqual(source.sets.map(set => ({ ...set, id: "" })));
    expect(copied.sets.every(set => source.sets.every(original => original.id !== set.id))).toBe(true);
    expect(copied.rule).toEqual({ ...source.rule, condition: { ...source.rule!.condition, setId: copied.sets[0].id } });
    expect(screen.getByLabelText("Exercise name")).toHaveFocus();
    expect(screen.getByRole("button", { name: "Collapse Squat" })).toHaveAttribute("aria-expanded", "true");
  });
  it("enforces the current day capacity when reusing exercises", () => {
    const initial = createBlankDocument();
    initial.weeks[0].days[0].exercises = Array.from({ length: 40 }, (_, i) => ({ ...createExercise(`Lift ${i + 1}`), sets: [] }));
    const changed = vi.fn();
    render(<Harness initial={initial} onDocumentChange={changed} />);
    fireEvent.click(screen.getByText("Reuse an exercise"));
    fireEvent.change(screen.getByRole("combobox", { name: "Exercise to reuse" }), { target: { value: initial.weeks[0].days[0].exercises[0].id } });
    expect(screen.getByRole("button", { name: "Add independent copy" })).toBeDisabled();
    expect(screen.getByText("This day has reached the exercise limit.")).toBeVisible();
    expect(changed).not.toHaveBeenCalled();
  });
  it("groups reps into one fieldset without changing targets and puts review warnings before workouts", () => {
    const initial = makePreset("double", "2026-10-13"); initial.name = "";
    render(<Harness initial={initial} />);
    const reps = screen.getByRole("group", { name: "Reps" });
    expect(within(reps).getByLabelText("Minimum reps")).toHaveValue(8);
    expect(within(reps).getByLabelText("Maximum reps")).toHaveValue(12);
    fireEvent.click(screen.getAllByRole("button", { name: "Review & start" })[0]);
    const warning = screen.getByLabelText("Program validation");
    const day = screen.getByRole("heading", { name: "Day A" });
    expect(warning.compareDocumentPosition(day) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
    expect(warning.compareDocumentPosition(screen.getByLabelText("Start date")) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
    expect(screen.getByRole("button", { name: "Start program" })).toBeDisabled();
  });
  it("builds a day and paired exercises without structure tabs", () => {
    render(<Harness />);
    fireEvent.change(screen.getByLabelText("Program name"), { target: { value: "Three day strength" } });
    fireEvent.click(screen.getByRole("button", { name: "Add superset" }));
    expect(screen.getByText("Superset A · 3 rounds")).toBeVisible();
    const cards = screen.getAllByRole("group", { name: /Exercise \d/ });
    fireEvent.change(within(cards[0]).getByLabelText("Exercise name"), { target: { value: "Squat" } });
    fireEvent.change(within(cards[0]).getByLabelText("Sets"), { target: { value: "5" } });
    expect(screen.getByText("Superset A · 5 / 3 sets")).toBeVisible();
    expect(within(cards[1]).getByLabelText("Sets")).toHaveValue(3);
    fireEvent.click(screen.getByRole("button", { name: "Add day" }));
    expect(screen.getByLabelText("Day name")).toHaveValue("Day 2");
    expect(screen.queryByRole("button", { name: "Prescriptions" })).toBeNull();
  });
  it("focuses newly added fields and announces reorder results", () => {
    render(<Harness />);
    fireEvent.click(screen.getByRole("button", { name: "Add superset" }));
    expect(screen.getAllByLabelText("Exercise name")[0]).toHaveFocus();
    fireEvent.click(screen.getByRole("button", { name: "Add day" }));
    expect(screen.getByLabelText("Day name")).toHaveFocus();
    fireEvent.click(screen.getByRole("button", { name: "Move day earlier" }));
    expect(screen.getByRole("status")).toHaveTextContent("Day moved earlier.");
  });
  it("shows advanced individual sets and preserves them through ordinary name edits", () => {
    render(<Harness initial={makePreset("top-backoff", "2026-10-13")} />);
    expect(screen.getAllByText(/Individual sets/)[0]).toBeVisible();
    expect(screen.getAllByText(/Top set/).length).toBeGreaterThan(0);
    const card = screen.getAllByRole("group", { name: /Exercise \d/ })[0];
    fireEvent.change(within(card).getByLabelText("Exercise name"), { target: { value: "Paused squat" } });
    expect(within(card).queryByLabelText("Sets")).toBeNull();
    fireEvent.click(within(card).getByText("Edit individual sets"));
    expect(within(card).getByLabelText("Set 1 minimum reps")).toBeVisible();
  });
  it("deduplicates technique cues while retaining full authored notes", () => {
    const initial = makePreset("manual-ab", "2026-10-13");
    const exercise = initial.weeks[0].days[0].exercises[0];
    exercise.notes = "Pause at the bottom.";
    exercise.sets.forEach(set => { set.notes = "Pause at the bottom. Choose your working weight before logging."; });
    render(<Harness initial={initial} />);
    const card = screen.getAllByRole("group", { name: /Exercise \d/ })[0];
    const cues = within(card).getByLabelText("Exercise cues");
    expect(cues.textContent?.match(/Pause at the bottom/g)).toHaveLength(1);
    fireEvent.click(within(card).getByText("Details", { selector: "summary" }));
    expect(within(card).getByLabelText("Exercise notes")).toHaveValue("Pause at the bottom.");
  });
  it("associates mixed effort targets with their sets and offers a footer review action", () => {
    render(<Harness initial={makePreset("top-backoff", "2026-10-13")} />);
    const card = screen.getAllByRole("group", { name: /Exercise \d/ })[0];
    const sets = within(card).getAllByRole("listitem");
    expect(sets[0]).toHaveTextContent(/Top set.*RPE 8/);
    expect(sets[1]).toHaveTextContent(/Back-off/);
    expect(within(card).getByLabelText("Exercise cues")).not.toHaveTextContent("Skipped exposures");
    const reviews = screen.getAllByRole("button", { name: "Review & start" });
    expect(reviews).toHaveLength(2);
    fireEvent.click(reviews[1]);
    expect(screen.getByRole("heading", { name: "Review your program" })).toBeVisible();
  });
  it("returns from review to the chosen day with focus", () => {
    const initial = makePreset("manual-ab", "2026-10-13");
    render(<Harness initial={initial} />);
    fireEvent.click(screen.getAllByRole("button", { name: "Review & start" })[0]);
    fireEvent.click(screen.getByRole("button", { name: `Edit ${initial.weeks[0].days[1].name}` }));
    expect(screen.getByLabelText("Day name")).toHaveValue(initial.weeks[0].days[1].name);
    expect(screen.getByLabelText("Day name")).toHaveFocus();
  });
  it("reviews workout content and actual schedule before starting", () => {
    render(<Harness initial={makePreset("manual-ab", "2026-10-13")} />);
    fireEvent.click(screen.getAllByRole("button", { name: "Review & start" })[0]);
    expect(screen.getByRole("heading", { name: "Review your program" })).toBeVisible();
    expect(screen.getByRole("button", { name: "Start program" })).toBeVisible();
    expect(screen.getByText(/First workout:/)).toBeVisible();
    fireEvent.click(screen.getByRole("button", { name: "Back to editing" }));
    expect(screen.getByLabelText("Day name")).toBeVisible();
  });
});
