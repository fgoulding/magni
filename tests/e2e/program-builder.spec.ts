import { expect, test } from "@playwright/test";
import { registerViaApi } from "./helpers";
import { readBuilderDraft, reviewBuilderForToday, saveBuilder, selectBuilderDay } from "./program-builder-helpers";

test("build a three-day superset program with direct fields, copy, reorder and optional weights", async ({ page }, info) => {
  test.setTimeout(120_000);
  await registerViaApi(page, "human-builder");
  expect((await page.request.post("/api/settings", { data: { timezone: "UTC" } })).ok()).toBe(true);
  await page.goto("/programs");
  for (const name of ["Choose a program", "Build a program", "Import JSON"]) await expect(page.getByRole("link", { name, exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Build a program", exact: true }).click();
  await page.getByLabel("Program name", { exact: true }).fill("My three-day full body");
  await page.getByLabel("Day name", { exact: true }).fill("Squat day");
  await page.getByRole("button", { name: "Add superset", exact: true }).click();
  const pair = page.getByRole("region", { name: "Superset A", exact: true });
  await pair.getByLabel("Exercise name", { exact: true }).nth(0).fill("Barbell squat");
  await pair.getByLabel("Exercise name", { exact: true }).nth(1).fill("One-arm dumbbell row");
  for (const index of [0, 1]) {
    await pair.getByLabel("Sets", { exact: true }).nth(index).fill("5");
    await pair.getByLabel("Minimum reps", { exact: true }).nth(index).fill(index ? "8" : "4");
    await pair.getByLabel("Maximum reps", { exact: true }).nth(index).fill(index ? "12" : "6");
    await expect(pair.getByLabel("Working weight (lb)", { exact: true }).nth(index)).toHaveValue("");
  }
  await pair.getByLabel("Working weight (lb)", { exact: true }).nth(1).fill("42.5");
  await expect(pair.getByRole("heading")).toHaveText("Superset A · 5 rounds");
  await page.getByRole("button", { name: "Copy day", exact: true }).click();
  await page.getByLabel("Day name", { exact: true }).fill("Bench day");
  await pair.getByLabel("Exercise name", { exact: true }).nth(0).fill("Bench press");
  await page.getByRole("button", { name: "Add day", exact: true }).click();
  await page.getByLabel("Day name", { exact: true }).fill("Deadlift day");
  await page.getByRole("button", { name: "Add exercise", exact: true }).click();
  await page.getByLabel("Exercise name", { exact: true }).fill("Deadlift");
  await page.getByRole("button", { name: "Move day earlier", exact: true }).click();
  await saveBuilder(page);
  const original = await readBuilderDraft(page);
  expect(original.document.weeks[0].days.map((day: { name: string }) => day.name)).toEqual(["Squat day", "Deadlift day", "Bench day"]);
  const [squat, , bench] = original.document.weeks[0].days;
  expect(squat.exercises.map((exercise: { sets: unknown[] }) => exercise.sets.length)).toEqual([5, 5]);
  expect(squat.exercises[1].baseLoad).toBe(42.5);
  expect(bench.exercises[0].id).not.toBe(squat.exercises[0].id);
  expect(bench.exercises[0].progressionKey).toBe(squat.exercises[0].progressionKey);
  await page.reload();
  await selectBuilderDay(page, 2);
  await expect(pair.getByLabel("Exercise name", { exact: true }).nth(0)).toHaveValue("Bench press");
  await expect(pair.getByLabel("Working weight (lb)", { exact: true }).nth(1)).toHaveValue("42.5");
  await page.screenshot({ path: info.outputPath("manual-builder.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await (await page.request.get("/api/programs")).json()).toEqual([]);
  await reviewBuilderForToday(page);
  await expect(page.getByRole("heading", { name: "Review your program", exact: true })).toBeVisible();
  await expect(page.getByText(/^First workout:/)).toContainText("Squat day");
  await page.getByRole("button", { name: "Start program", exact: true }).click();
  await expect(page.getByText("Program activated", { exact: true })).toBeVisible();
  const programs = await (await page.request.get("/api/programs")).json();
  expect(programs).toHaveLength(1);
  await page.getByRole("link", { name: "Train this program", exact: true }).click();
  const started = page.waitForResponse(response => /\/api\/programs\/\d+\/sessions$/.test(response.url()) && response.request().method() === "POST");
  await page.getByRole("button", { name: "Start Workout", exact: true }).click();
  const session = await (await started).json();
  expect(session.sets).toHaveLength(10);
  expect(session.sets.filter((set: { exercise_name: string }) => set.exercise_name === "One-arm dumbbell row").every((set: { calculated_weight: number }) => set.calculated_weight === 42.5)).toBe(true);
  await page.getByRole("button", { name: "Save set 1", exact: true }).first().click();
  await expect(page.getByRole("button", { name: "Undo set 1", exact: true }).first()).toBeEnabled();
  await page.reload();
  await expect(page.getByRole("button", { name: "Undo set 1", exact: true }).first()).toBeEnabled();
});
